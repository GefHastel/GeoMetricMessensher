/* ============================================================================
   GeoMetric — «служба обновления» внутри браузера (service worker).
   ----------------------------------------------------------------------------
   Зачем это нужно:
     Браузер старается экономить интернет и держит копии файлов приложения.
     Из-за этого после выпуска новой версии человек мог видеть СТАРЫЙ интерфейс,
     пока не нажмёт Ctrl+F5. Эта служба решает проблему: приложение всегда
     старается взять свежие файлы из сети, а копию держит только на случай,
     когда интернета нет.

   Правила простые:
     1) Сначала сеть, потом копия. Сайт и его файлы всегда самые новые.
     2) Переписка и файлы чатов не кэшируются никогда — только оформление и код.
     3) У каждой версии своё имя кэша: при обновлении старая копия стирается.
   ========================================================================== */

const VERSION = "1.0.0";                 // версия интерфейса (для подписи кэша)
const CACHE = "geometric-shell-" + VERSION;   // имя кэша: при выпуске новой версии меняется

const SHELL = [
  // «Оболочка» приложения: без этих файлов интерфейс не откроется.
  // Пути относительные: приложение носит файлы с собой (в APK и в EXE).
  "./",
  "style.css",
  "design.css",
  "app.js",
  "crypto.js",
  "i18n.js",
  "qrcode.min.js",
  "socket.io.min.js",
  "manifest.webmanifest",
  "icons/icon-192.png",
];

self.addEventListener("install", (event) => {
  // Установка новой версии: сразу становимся главными, не дожидаясь закрытия вкладок.
  event.waitUntil(
    caches.open(CACHE).then((кэш) => кэш.addAll(SHELL).catch(() => null)).then(() => self.skipWaiting())
    // addAll — складываем файлы; skipWaiting — новая версия включается немедленно.
  );
});

self.addEventListener("activate", (event) => {
  // Активация: стираем ВСЕ прежние копии, чтобы старая версия не могла вернуться.
  event.waitUntil(
    caches.keys()
      .then((имена) => Promise.all(имена.filter((имя) => имя !== CACHE).map((имя) => caches.delete(имя))))
      .then(() => self.clients.claim())          // сразу берём управление открытыми страницами
      .then(() => self.clients.matchAll({ type: "window" }))
      .then((окна) => окна.forEach((окно) => окно.postMessage({ type: "gm-updated", version: VERSION })))   // сообщаем страницам: вышло обновление
  );
});

self.addEventListener("fetch", (event) => {
  // Перехватываем запросы страницы.
  const запрос = event.request;                                   // сам запрос
  if (запрос.method !== "GET") return;                            // менять и загружать файлы не мешаем
  const url = new URL(запрос.url);                                // разбираем адрес
  if (url.origin !== location.origin) return;                     // чужие адреса не трогаем
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/uploads/") || url.pathname.startsWith("/socket.io/")) {
    return;                                                       // переписку, файлы и связь с сервером НЕ кэшируем
  }

  // Главная страница: всегда берём свежую версию из сети (иначе браузер покажет старый интерфейс).
  if (запрос.mode === "navigate") {
    event.respondWith(
      fetch(запрос)
        .then((ответ) => {
          const копия = ответ.clone();                            // делаем копию для офлайна
          caches.open(CACHE).then((кэш) => кэш.put("./", копия)); // обновляем копию главной страницы
          return ответ;                                           // отдаём свежую страницу
        })
        .catch(() => caches.match("./"))                          // интернета нет — отдаём копию
    );
    return;                                                       // дальше не идём
  }

  // Остальные файлы интерфейса: тоже сначала сеть, копия — только запасной вариант.
  event.respondWith(
    fetch(запрос)
      .then((ответ) => {
        if (ответ && ответ.ok) {                                  // удачный ответ —
          const копия = ответ.clone();                            //   обновляем копию для офлайна
          caches.open(CACHE).then((кэш) => кэш.put(запрос, копия));
        }
        return ответ;                                             // отдаём свежие данные
      })
      .catch(() => caches.match(запрос).then((копия) => копия || caches.match("./")))   // сети нет — отдаём копию
  );
});
